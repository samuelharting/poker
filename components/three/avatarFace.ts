/**
 * Moustache tip lift (eye radii) for a mouth corner, measured from that corner's RESTING height (so a
 * resting smirk or idle drift never turns into a sneer): a frown droops the tips, a smile lifts them,
 * both capped by the moustache's size; a gaping (not smiling) mouth pulls them down a little.
 * `rest` levels an upturned crescent at rest (from the moustache's measured shape).
 */
function moustacheLift(corner: number, restCorner: number, halfWidth: number, rest: number, smirk: number) {
  // A small dead zone: idle drift and faint in-hand asymmetry leave the moustache level.
  const raw = corner - restCorner
  const d = raw > 0 ? Math.max(0, raw - 0.1) : Math.min(0, raw + 0.1)
  // The lifted side of a smirk rises further and faster (the corner itself is hidden under the hair).
  // It also drops the rest levelling on that side, so the tip kinks up past the moustache's own crescent.
  const upCap = (0.28 + 0.2 * smirk) * halfWidth
  const bend = d < 0 ? Math.max(-Math.min(0.38 * halfWidth, 0.5), d * 0.9) : Math.min(upCap, d * (0.55 + 0.45 * smirk))
  return rest * (1 - smirk) + bend
}

/** Largest moustache tip motion per second (eye radii), so a frame hitch never snaps it. */
const MOUSTACHE_TIP_RATE = 3

/** Applies emotion, blink, gaze, lids, brows, mouth and skin decals for this frame. */
export function updateAvatarFace(face: AvatarFaceRig, input: FaceInput) {
  if (!face.sceneHooked) hookSkeletonSync(face)
  else if (face.scene) ensureSceneHook(face.scene)
  if (input.skip) return
  const costStart = process.env.NODE_ENV !== 'production' ? performance.now() : 0
  updateAvatarFaceInner(face, input)
  if (costStart) {
    const cost = ((globalThis as { __faceCost?: { ms: number; calls: number; cur: number } }).__faceCost ??= { ms: 0, calls: 0, cur: 0 })
    const spent = performance.now() - costStart
    cost.ms += spent
    cost.cur += spent
    cost.calls += 1
  }
}

function updateAvatarFaceInner(face: AvatarFaceRig, input: FaceInput) {
  const debug = readDebug()
  const state = face.state
  const delta = input.delta === input.delta ? Math.min(0.1, Math.max(0, input.delta)) : 0.016
  const instant = input.reducedMotion || Boolean(debug?.instant)
  state.frame += 1
  // Far faces update at a reduced rate already (director); beyond that skip decals every other update.
  const skipDetail = (input.distance ?? 0) > 9 && (state.frame & 1) === 1

  // ---- emotion ----
  const weights = state.debugWeights
  let debugWeights: Float32Array | null = null
  if (debug?.emotion !== undefined) {
    weights.fill(0)
    if (typeof debug.emotion === 'string') {
      const name = (LEGACY_MOOD_TO_EMOTION as Record<string, FaceEmotion | null>)[debug.emotion] ?? debug.emotion
      const index = name ? EMOTION_INDEX[name as FaceEmotion] : undefined
      if (index !== undefined) weights[index] = 1
    } else {
      for (const [key, value] of Object.entries(debug.emotion)) {
        const index = EMOTION_INDEX[key as FaceEmotion]
        if (index !== undefined) weights[index] = value
      }
    }
    debugWeights = weights
  } else if (!input.hasContext) {
    weights.fill(0)
    const legacy = input.mood ? LEGACY_MOOD_TO_EMOTION[input.mood] : null
    if (legacy) weights[EMOTION_INDEX[legacy]] = 1
    debugWeights = weights
  }
  if (debug?.context) Object.assign(face.context, debug.context)
  const distance = input.distance !== undefined && Number.isFinite(input.distance) ? input.distance : 0
  face.emotion.boost = clamp((distance - 4) / 6, 0, 1) * 0.5
  updateEmotion(face.emotion, face.context, face.personality, delta, instant, debugWeights)
  const p = face.emotion.params
  if (debug?.channels) {
    for (const [key, value] of Object.entries(debug.channels)) {
      const channel = (CH as Record<string, number>)[key]
      if (channel !== undefined) p[channel] = value
    }
  }
  state.time = face.emotion.time
  // How lopsided the smile is beyond the resting habit (+: the dominant "A" side is up), 0..1.
  let hairSmirk = 0
  if (face.mouth.facialHair) {
    // A smirk corner hides under the moustache: carry it with that side's cheek and lower lid.
    const asym = p[CH.smileA]! - p[CH.smileB]! - 0.4 * face.personality.baseSmile
    hairSmirk = clamp((Math.abs(asym) - 0.12) / 0.45, 0, 1) * Math.sign(asym)
    if (hairSmirk > 0) p[CH.lidLA] = Math.min(1, p[CH.lidLA]! + hairSmirk * 0.32)
    else if (hairSmirk < 0) p[CH.lidLB] = Math.min(1, p[CH.lidLB]! - hairSmirk * 0.32)
    // The moustache hides most of the mouth, so the smile also reads through cheeks and eyes.
    const smile = Math.max(0, (p[CH.smileA]! + p[CH.smileB]!) * 0.5 - 0.08)
    p[CH.lidLA] = Math.min(1, p[CH.lidLA]! + smile * 0.32)
    p[CH.lidLB] = Math.min(1, p[CH.lidLB]! + smile * 0.32)
    // ...and so does a frown: brows push further from rest, the furrow deepens, the upper lids
    // sag and the lower lids tighten, so a sad or angry face never leans on the mouth alone.
    const frown = clamp(-(p[CH.smileA]! + p[CH.smileB]!) * 0.5, 0, 1)
    if (frown > 0.01) {
      const gain = 1 + frown * 0.45
      p[CH.browIA] = p[CH.browIA]! * gain
      p[CH.browIB] = p[CH.browIB]! * gain
      p[CH.browOA] = p[CH.browOA]! * gain
      p[CH.browOB] = p[CH.browOB]! * gain
      p[CH.furrow] = Math.min(1, p[CH.furrow]! + frown * 0.3)
      p[CH.lidUA] = p[CH.lidUA]! - frown * 0.1
      p[CH.lidUB] = p[CH.lidUB]! - frown * 0.1
      p[CH.lidLA] = Math.min(1, p[CH.lidLA]! + frown * 0.15)
      p[CH.lidLB] = Math.min(1, p[CH.lidLB]! + frown * 0.15)
    }
    p[CH.smileA] += FACIAL_HAIR_SMILE_BIAS
    p[CH.smileB] += FACIAL_HAIR_SMILE_BIAS
  }

  // ---- blink ----
  const arousal = emotionArousal(face.emotion)
  const heavy = emotionHeaviness(face.emotion)
  const still = Boolean(debug?.still)
  const forced = debug?.emotion !== undefined ? (debug.blink ?? 0) : Math.max(input.blink, debug?.blink ?? 0)
  let blink = instant || still ? 0 : updateBlink(face.emotion, face.personality, face.gazeState.blinkKick)
  face.gazeState.blinkKick = false
  blink = Math.max(blink, forced)

  // ---- gaze ----
  const gazeState = face.gazeState
  const headWorld = face.headBone.matrixWorld
  scratchInv.copy(headWorld).invert()
  if (debug?.gaze && GAZE_DEBUG[debug.gaze] !== undefined) {
    gazeState.kind = GAZE_DEBUG[debug.gaze]!
    gazeState.fixUntil = face.emotion.time + 1e6
  } else if (gazeState.fixUntil > face.emotion.time + 1e5) {
    gazeState.fixUntil = face.emotion.time
  }
  const gazeOpts = face.gazeOpts
  gazeOpts.instant = instant
  gazeOpts.heavy = heavy
  gazeOpts.fallbackYaw = clamp(input.lookX, -1, 1) * 0.3
  gazeOpts.fallbackPitch = -clamp(input.lookY, -1, 1) * 0.2
  gazeOpts.tripping = face.context.tripping
  gazeOpts.drunk = face.context.drunk
  gazeOpts.closed = face.context.passedOut
  gazeOpts.still = still
  const kicked = updateGaze(
    gazeState,
    input.hasContext || debug?.gaze ? face.targets : null,
    scratchInv,
    face.gazeEyes,
    face.personality,
    face.emotion.time,
    delta,
    gazeOpts
  )
  // Big gaze shifts are usually accompanied by a blink.
  // A NaN in the gaze (bad target position) must never stick: recover to a neutral look.
  for (let e = 0; e < 2; e += 1) {
    if (!(gazeState.yaw[e]! === gazeState.yaw[e]!)) gazeState.yaw[e] = 0
    if (!(gazeState.pitch[e]! === gazeState.pitch[e]!)) gazeState.pitch[e] = 0
  }
  if (kicked && !instant && !still && face.emotion.time - gazeState.jumpedAt < 0.05) gazeState.blinkKick = faceRandomBlink(face)

  if (debug?.cam && Math.abs(debug.cam.seed - state.seed) < 1e-9) lockDebugCamera(face, debug.cam)
  // ---- dim (folded players sit in shade) ----
  const dimTarget = input.folded ? 0.62 : 1
  state.dim += (dimTarget - state.dim) * (instant ? 1 : 1 - Math.exp(-delta * 5))

  // Key light in Head space, for the catch-lights.
  scratchLight.copy(LIGHT_WORLD).transformDirection(scratchInv)

  // ---- eyes ----
  const time = face.emotion.time
  const smirkSide = face.personality.smirkSide
  const pupilNoise = still ? 0 : Math.sin(time * 1.9 + state.seed * 30) * 0.006 + Math.sin(time * 4.3 + state.seed * 11) * 0.003
  const pupilBase = 0.19 + p[CH.pupil]! * 0.085 + pupilNoise
  state.pupil = pupilBase
  const redness = clamp(p[CH.red]! + 0.14 * (1 - Math.min(1, blink)) * heavy, 0, 1)
  for (let i = 0; i < face.eyes.length; i += 1) {
    const eye = face.eyes[i]!
    const isA = eye.side === smirkSide
    const lidU = isA ? p[CH.lidUA]! : p[CH.lidUB]!
    const lidL = isA ? p[CH.lidLA]! : p[CH.lidLB]!
    const browI = isA ? p[CH.browIA]! : p[CH.browIB]!
    const browO = isA ? p[CH.browOA]! : p[CH.browOB]!
    const u = eye.uniforms
    // An eye roll takes over from wherever the eyes were looking: up and over, relative to straight ahead.
    const rollHand = 1 - face.emotion.rollEnv
    const eyePitch = Math.min(0.46, gazeState.pitch[i]! * rollHand + face.emotion.rollPitch)
    gazeVector(gazeState.yaw[i]! * rollHand + face.emotion.rollYaw, eyePitch, u.uGaze.value)
    // Lids follow the eyeball: looking down lowers the upper lid, up lifts it.
    const follow = eyePitch * 0.17
    const open = clamp((lidU + follow) * (1 - blink), 0, 1.32)
    const lower = clamp(lidL, -0.4, 1)
    const lowerAmp = 0.17 * (1 - 0.85 * lower) * (1 - 0.3 * blink)
    const tilt = 0.055 + 0.035 * (browO - browI) * 0.5
    u.uAper.value.set(0.3, Math.max(0.005, lowerAmp), EYE_APERTURE_HALF_WIDTH, tilt)
    u.uState.value.set(open, 0.85 + 0.2 * face.personality.expressiveness, 0.5 + 0.22 * (1 - Math.min(1, open)), state.dim)
    u.uIris.value.set(0.5, clamp(pupilBase * 1.12, 0.11, 0.34), 0.62, 1 + 0.5 * p[CH.sweat]! + 0.25 * heavy)
    // Catch-light offset from the key light, expressed in the eye's local axes.
    const lx = scratchLight.x * (eye.side === 1 ? 1 : 1) * 0.85
    const ly = scratchLight.y * 0.85
    const len = Math.hypot(lx, ly) || 1
    const scale = Math.min(1, 0.62 / len)
    u.uLight.value.set(lx * scale + (eye.side === 1 ? -0.05 : 0.05), ly * scale, redness, 1)
    u.uSclera.value.setRGB(0.95, 0.925 - 0.02 * p[CH.pallor]!, 0.885 - 0.03 * p[CH.pallor]!)
  }
  if (face.skinSource) {
    for (const follower of face.skinFollowers) follower.color.copy(face.skinSource.color)
  }
  // ---- brows ----
  if (!skipDetail) {
    const bp = state.browParams
    const eyeIsA0 = face.eyes[0]!.side === smirkSide
    const blinkDip = blink * 0.5
    bp.inner[0] = eyeIsA0 ? p[CH.browIA]! : p[CH.browIB]!
    bp.inner[1] = eyeIsA0 ? p[CH.browIB]! : p[CH.browIA]!
    bp.outer[0] = eyeIsA0 ? p[CH.browOA]! : p[CH.browOB]!
    bp.outer[1] = eyeIsA0 ? p[CH.browOB]! : p[CH.browOA]!
    bp.arch = p[CH.arch]!
    bp.furrow = p[CH.furrow]!
    const lowerA = clamp(eyeIsA0 ? p[CH.lidLA]! : p[CH.lidLB]!, 0, 1)
    const lowerB = clamp(eyeIsA0 ? p[CH.lidLB]! : p[CH.lidLA]!, 0, 1)
    bp.dip[0] = blinkDip + lowerA * 0.35
    bp.dip[1] = blinkDip + lowerB * 0.35
    // Thicker brows on far faces (and dark skin) so they still carry the expression.
    bp.thick = (1 + 0.5 * clamp((distance - 4) / 8, 0, 1)) * face.browContrast
    updateBrows(face.overlay, bp)

    // ---- mouth ----
    const shape = state.mouthShape
    const smileA = p[CH.smileA]!
    const smileB = p[CH.smileB]!
    // Eye index 0 is the +x side, so it owns the mouth's right corner.
    shape.cornerR = smirkSide === 1 ? smileA : smileB
    shape.cornerL = smirkSide === 1 ? smileB : smileA
    // A yawn stretches the jaw past the channel's range (a surprised "O" tops out at 0.9).
    shape.open = p[CH.open]! * (1 + 0.4 * face.context.yawn)
    if (face.hairShade) {
      // Neutral and frowning faces get the full lip shadow; a smile lets the moustache stay bright.
      const smileAvgHair = (smileA + smileB) * 0.5
      face.hairShade.uniforms.uHairShade.value.x = clamp(0.4 - smileAvgHair * 0.9 + p[CH.press]! * 0.3 + p[CH.furrow]! * 0.2, 0, 1)
    }
    // A wide-open mouth (surprise, laugh) is symmetric: pull the two corners together.
    const evenOut = Math.min(1, shape.open * 1.6)
    const cornerMean = (shape.cornerL + shape.cornerR) * 0.5
    shape.cornerL += (cornerMean - shape.cornerL) * evenOut
    shape.cornerR += (cornerMean - shape.cornerR) * evenOut
    if (face.hairShade) {
      // The moustache follows the mouth corners (without the facial-hair smile bias): tips droop on
      // a frown, one side lifts on a smirk, the upper lip rises when the mouth opens or snarls.
      const bend = face.hairShade.uniforms.uHairBend.value
      const person = face.personality
      const restA = 0.05 + person.baseSmile + FACIAL_HAIR_SMILE_BIAS
      const restB = 0.05 + person.baseSmile * 0.6 + FACIAL_HAIR_SMILE_BIAS
      const width = bend.z
      const level = -clamp((face.hairShade.moustache?.tipRise ?? 0) * 0.85, 0, 0.4 * width)
      const smirkR = Math.max(0, smirkSide === 1 ? hairSmirk : -hairSmirk)
      const smirkL = Math.max(0, smirkSide === 1 ? -hairSmirk : hairSmirk)
      const wantL = moustacheLift(shape.cornerL, smirkSide === 1 ? restB : restA, width, level, smirkL)
      const wantR = moustacheLift(shape.cornerR, smirkSide === 1 ? restA : restB, width, level, smirkR)
      // An open, unsmiling mouth (surprise, shock) lifts the moustache's middle so an "O" shows under it.
      const unsmiling = clamp(1 - 2 * Math.max(0, (shape.cornerL + shape.cornerR) * 0.5 - FACIAL_HAIR_SMILE_BIAS), 0, 1)
      const wantC = shape.open * (0.12 + 0.1 * unsmiling) + p[CH.teeth]! * 0.04 - p[CH.press]! * 0.04
      if (instant) {
        bend.x = wantL
        bend.y = wantR
        bend.w = wantC
      } else {
        const step = MOUSTACHE_TIP_RATE * Math.min(delta, 0.05)
        bend.x += clamp(wantL - bend.x, -step, step)
        bend.y += clamp(wantR - bend.y, -step, step)
        bend.w += clamp(wantC - bend.w, -step, step)
      }
      const clip = face.mouth.hairClip
      if (clip) {
        clip.liftL = bend.x * face.eyes[0]!.radius
        clip.liftR = bend.y * face.eyes[0]!.radius
        clip.centre = bend.w * face.eyes[0]!.radius
      }
    }
    shape.width = p[CH.width]!
    shape.press = p[CH.press]!
    shape.purse = p[CH.purse]!
    shape.teeth = p[CH.teeth]!
    if (face.mouth.facialHair) {
      // Under a moustache a gasp should read as a round "O", not a wide toothy "ah": narrower,
      // a touch rounder, fewer teeth.
      const unsmilingO = clamp(1 - 2 * Math.max(0, (smileA + smileB) * 0.5 - FACIAL_HAIR_SMILE_BIAS), 0, 1)
      const gasp = clamp(shape.open * 1.4, 0, 1) * unsmilingO
      shape.width -= 0.3 * gasp
      shape.purse = Math.min(1, shape.purse + 0.25 * gasp)
      shape.teeth *= 1 - 0.6 * gasp
    }
    shape.shift = p[CH.jaw]! * smirkSide * (1 - evenOut)
    ;(face.mouth.mesh.material as THREE.MeshToonMaterial).color.setScalar(state.dim)
    const skinForMouth = face.skinSource ? face.skinSource.color : scratchSkin
    updateMouth(face.mouth, shape, skinForMouth)
  }

  // ---- skin decals ----
  if (!skipDetail) {
    const a = state.alphas
    const smileAvg = (p[CH.smileA]! + p[CH.smileB]!) * 0.5
    const warmth = face.personality.warmth
    const sweat = p[CH.sweat]!
    // Drink shows as rosy cheeks here (the skin itself only warms a little, see flushCheeks).
    const flush = clamp(face.context.drunk / 10, 0, 1)
    const blush = Math.min(0.2 + 0.22 * flush, 0.04 + 0.02 * warmth + p[CH.blush]! * 0.3 + Math.max(0, smileAvg) * 0.04 + flush * 0.3)
    a.blushA = blush
    a.blushB = blush
    const tired = clamp(p[CH.pallor]! * 0.7 + p[CH.red]! * 0.35 + (1 - p[CH.lidUA]!) * 0.14 + heavy * 0.2 + arousal * 0.08, 0, 1)
    a.bagA = 0.015 + tired * 0.2
    a.bagB = 0.015 + tired * 0.2
    a.nose = 0.03 + 0.02 * Math.max(0, warmth) + sweat * 0.34
    a.forehead = 0.035 + sweat * 0.32
    const cheekLift = 0.012 + sweat * 0.22 + Math.max(0, smileAvg) * (face.mouth.facialHair ? 0.12 : 0.05)
    a.cheekA = cheekLift
    a.cheekB = cheekLift
    a.pallor = Math.min(0.25, p[CH.pallor]! * 0.3)
    const wrinkle = p[CH.wrinkle]!
    // creaseA sits on the +x side, which belongs to whichever of A/B that side is.
    const smilePlus = smirkSide === 1 ? p[CH.smileA]! : p[CH.smileB]!
    const smileMinus = smirkSide === 1 ? p[CH.smileB]! : p[CH.smileA]!
    const creaseGain = face.mouth.facialHair ? 1.7 : 1
    // Under a moustache the smirk side's cheek crease carries the lopsided smile.
    const smirkPlus = (smirkSide === 1 ? hairSmirk : -hairSmirk)
    a.creaseA = Math.max(0, smilePlus - 0.15) * 0.34 * creaseGain + wrinkle * 0.2 + Math.max(0, smirkPlus) * 0.22
    a.creaseB = Math.max(0, smileMinus - 0.15) * 0.34 * creaseGain + wrinkle * 0.2 + Math.max(0, -smirkPlus) * 0.22
    a.furrow = p[CH.furrow]! * 0.26
    a.noseWrinkle = Math.max(0, wrinkle - 0.1) * 0.5
    updateOverlayColors(face.overlay, a, 0.94, state.dim)
  }
}

const camMid = new THREE.Vector3()
const camFwd = new THREE.Vector3()
const camMat = new THREE.Matrix4()

/** Dev only: keeps the debug camera looking straight into this face, every frame. */
function lockDebugCamera(face: AvatarFaceRig, cam: NonNullable<FaceDebug['cam']>) {
  const stage = document.querySelector('.desktop-3d-stage') as (Element & { __pokerRuntime?: { debugCamera: unknown } }) | null
  const runtime = stage?.__pokerRuntime
  if (!runtime) return
  camMat.copy(face.headBone.matrixWorld)
  camMid.copy(face.eyes[0]!.root.position).add(face.eyes[1]!.root.position).multiplyScalar(0.5).applyMatrix4(camMat)
  camFwd.copy(face.overlay.basis.forward).transformDirection(camMat)
  const yaw = cam.yaw ?? 0
  const c = Math.cos(yaw)
  const s = Math.sin(yaw)
  const fx = camFwd.x * c + camFwd.z * s
  const fz = -camFwd.x * s + camFwd.z * c
  runtime.debugCamera = {
    position: [camMid.x + fx * cam.dist, camMid.y + camFwd.y * cam.dist, camMid.z + fz * cam.dist],
    lookAt: [camMid.x, camMid.y - 0.06, camMid.z],
    fov: cam.fov ?? 30,
  }
}

function faceRandomBlink(face: AvatarFaceRig) {
  // Roughly 60% of big gaze jumps come with a blink (deterministic per face and moment).
  return faceHash01(face.emotion.time * 3.1 + face.state.seed * 7) < 0.6
}

export function disposeAvatarFace(face: AvatarFaceRig | null) {
  if (!face) return
  face.hiddenMaterials.forEach(material => { material.visible = true })
  face.restoreSkin?.()
  face.hairShade?.restore()
  for (const skeleton of face.skeletons) unregisterSkeleton(skeleton)
  face.eyes.forEach(eye => eye.root.removeFromParent())
  face.overlay.mesh.removeFromParent()
  face.mouth.mesh.removeFromParent()
  face.materials.forEach(material => material.dispose())
  face.geometries.forEach(geometry => geometry.dispose())
  face.overlay.mesh.geometry.dispose()
  releaseOverlayAtlas()
}

/** Exposed for the debug snapshot tool (dev only). */
export function describeFace(face: AvatarFaceRig) {
  return {
    eyewear: face.eyewear,
    eyeRadius: face.eyes[0]?.radius,
    moustache: face.hairShade?.moustache
      ? { halfWidth: face.hairShade.moustache.halfWidth, tipRise: face.hairShade.moustache.tipRise, bend: face.hairShade.uniforms.uHairBend.value.toArray() }
      : null,
    personality: face.personality,
    channels: Array.from(face.emotion.params),
    gaze: { kind: face.gazeState.kind, yaw: [...face.gazeState.yaw], pitch: [...face.gazeState.pitch] },
  }
}
