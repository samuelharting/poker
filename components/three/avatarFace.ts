/**
 * Expressive faces for the rigged avatars.
 *
 * The source models paint tiny eyes and brows onto the head. We locate those
 * painted regions in the skinned mesh (by material name), hide them, and mount
 * real, procedural features on the Head bone at the same spots:
 *   - eyes (avatarFaceEyes): one shader dome each, with real lids that close,
 *     almond shape, lashes, iris detail, dilating pupil, wet catch-lights;
 *   - brows + skin decals (avatarFaceOverlay): one mesh for both brows, blush,
 *     eye bags, sheen, pallor and crease lines;
 *   - mouth (avatarFaceMouth): lips, teeth, tongue, asymmetric corners.
 * Emotion (avatarFaceEmotion), gaze (avatarFaceGaze) and the per-seat director
 * (avatarFaceDirector) drive them. Cost per face: 2 eye draws + 1 overlay + 1 mouth.
 */

export type FaceMood = 'neutral' | 'focused' | 'surprised' | 'happy' | 'sad' | 'bored'

export interface EyeRig {
  /** Positioned/rotated/scaled (uniform, = eye radius) on the Head bone; +Z faces out of the head. */
  root: THREE.Group
  dome: THREE.Mesh
  uniforms: EyeUniforms
  /** Head-space eye radius (the nominal radius, before glasses fitting). */
  radius: number
  side: 1 | -1
}

