/** Collects the bind-pose positions (in Head-bone space) of vertices painted with a material. */
function collectRegion(
  model: THREE.Object3D,
  headBone: THREE.Bone,
  materialPattern: RegExp
): THREE.Vector3[] {
  const points: THREE.Vector3[] = []
  model.traverse(object => {
    const mesh = object as THREE.SkinnedMesh
    if (!mesh.isSkinnedMesh || !mesh.material) return
    const headIndex = mesh.skeleton.bones.indexOf(headBone)
    if (headIndex < 0) return
    const toHead = new THREE.Matrix4().multiplyMatrices(mesh.skeleton.boneInverses[headIndex]!, mesh.bindMatrix)
    const position = mesh.geometry.getAttribute('position')
    const index = mesh.geometry.getIndex()
    const materials = Array.isArray(mesh.material) ? mesh.material : [mesh.material]
    // GLTF splits multi-material meshes into one primitive per material, so a
    // single-material mesh has no groups: treat it as one group spanning it all.
    const groups = mesh.geometry.groups.length > 0
      ? mesh.geometry.groups
      : [{ start: 0, count: index ? index.count : position.count, materialIndex: 0 }]
    for (const group of groups) {
      const material = materials[group.materialIndex ?? 0]
      if (!material || !materialPattern.test(material.name)) continue
      for (let cursor = group.start; cursor < group.start + group.count; cursor += 1) {
        const vertex = index ? index.getX(cursor) : cursor
        points.push(new THREE.Vector3().fromBufferAttribute(position, vertex).applyMatrix4(toHead))
      }
    }
  })
  return points
}

function splitBySide(points: THREE.Vector3[]) {
  const center = points.reduce((sum, point) => sum.add(point), new THREE.Vector3()).divideScalar(Math.max(1, points.length))
  const left = points.filter(point => point.x < center.x)
  const right = points.filter(point => point.x >= center.x)
  const box = (list: THREE.Vector3[]) => new THREE.Box3().setFromPoints(list)
  return { center, left: left.length ? box(left) : null, right: right.length ? box(right) : null }
}

/** Hides the painted eyes/brows by matching them to the skin tone. */
function paintOver(materials: readonly THREE.Material[], pattern: RegExp, skin: THREE.Color | null) {
  if (!skin) return
  for (const material of materials) {
    const tinted = material as THREE.MeshToonMaterial
    if (pattern.test(material.name) && tinted.color) tinted.color.copy(skin)
  }
}

/**
 * Skinned meshes and the things rigidly attached to bones (eyes, brows, mouth, glasses, hats) must
 * agree on the pose every frame. three.js refreshes a skeleton at most once per renderer frame
 * counter, and the shadow pass (which only runs on some frames here) bumps that counter and
 * refreshes the skeleton itself. On the frame after a shadow pass the main pass therefore reuses
 * bone matrices from the PREVIOUS frame, while rigid children use the current ones: the skin lags
 * one frame and, during quick head motion, swallows everything mounted on it (blank faces).
 * Fix: refresh every avatar skeleton from the final bone matrices right before each render
 * (Scene.onBeforeRender runs after the matrices are updated and before the skeletons are read).
 */
interface SyncedSkeleton {
  skeleton: THREE.Skeleton
  update: () => void
  stamp: number
}
const syncedSkeletons: SyncedSkeleton[] = []
let syncToken = 0

/** Our pre-render hook per scene, plus a watchdog (see ensureSceneHook). */
interface SceneHook {
  hook: NonNullable<THREE.Object3D['onBeforeRender']>
  /** Times the hook ran; `seen` is the value at the last check, `stall` the checks since it moved. */
  runs: number
  seen: number
  stall: number
}
const sceneHooks = new WeakMap<THREE.Object3D, SceneHook>()

function collectSkeletons(model: THREE.Object3D) {
  const list: THREE.Skeleton[] = []
  model.traverse(object => {
    const mesh = object as THREE.SkinnedMesh
    if (mesh.isSkinnedMesh && mesh.skeleton && !list.includes(mesh.skeleton)) list.push(mesh.skeleton)
  })
  return list
}

function registerSkeleton(skeleton: THREE.Skeleton) {
  if (syncedSkeletons.some(entry => entry.skeleton === skeleton)) return
  const entry: SyncedSkeleton = { skeleton, update: skeleton.update, stamp: -1 }
  // three's render pass calls skeleton.update() again after our refresh: skip that duplicate work
  // (same frame, same bones) so the sync is free. Outside a synced frame it behaves as before.
  skeleton.update = function (this: THREE.Skeleton) {
    if (entry.stamp === syncToken) return
    entry.update.call(this)
  }
  syncedSkeletons.push(entry)
}

function unregisterSkeleton(skeleton: THREE.Skeleton) {
  const index = syncedSkeletons.findIndex(entry => entry.skeleton === skeleton)
  if (index < 0) return
  delete (skeleton as { update?: () => void }).update // back to the prototype method
  syncedSkeletons.splice(index, 1)
}

function beforeSceneRender() {
  // (dev switch for A/B measurements: window.__faceNoSkeletonSync = true)
  if (process.env.NODE_ENV !== 'production' && (globalThis as { __faceNoSkeletonSync?: boolean }).__faceNoSkeletonSync) {
    syncToken += 1
    return
  }
  syncToken += 1
  for (let i = 0; i < syncedSkeletons.length; i += 1) {
    const entry = syncedSkeletons[i]!
    entry.update.call(entry.skeleton)
    entry.stamp = syncToken
  }
}

/** Wraps whatever scene.onBeforeRender currently is so the skeleton sync runs first-class after it. */
function installSceneHook(scene: THREE.Object3D) {
  const previous = scene.onBeforeRender
  const entry: SceneHook = {
    hook: function (this: THREE.Object3D, renderer, sceneArg, camera, geometry, material, group) {
      previous.call(this, renderer, sceneArg, camera, geometry, material, group)
      entry.runs += 1
      beforeSceneRender()
    },
    runs: 0,
    seen: 0,
    stall: 0,
  }
  sceneHooks.set(scene, entry)
  scene.onBeforeRender = entry.hook
}

/**
 * Watchdog, run cheaply on every face update: if some other code REPLACED scene.onBeforeRender
 * without chaining ours (faces would float off their heads), wrap the new one again. A hook that
 * chains ours keeps the run counter moving and is left alone; a paused renderer (no runs, but our
 * hook still installed) is left alone too, so wrappers never pile up.
 */
function ensureSceneHook(scene: THREE.Object3D) {
  const entry = sceneHooks.get(scene)
  if (!entry) {
    installSceneHook(scene)
    return
  }
  if (entry.runs !== entry.seen) {
    entry.seen = entry.runs
    entry.stall = 0
    return
  }
  entry.stall += 1
  if (entry.stall > 8 && scene.onBeforeRender !== entry.hook) installSceneHook(scene)
}

function hookSkeletonSync(face: AvatarFaceRig) {
  let node: THREE.Object3D = face.headBone
  while (node.parent) node = node.parent
  const scene = node as THREE.Scene
  if (!scene.isScene) return // not mounted yet: try again next frame
  face.sceneHooked = true
  face.scene = scene
  for (const skeleton of face.skeletons) registerSkeleton(skeleton)
  ensureSceneHook(scene)
}

const RIGGED_ACCESSORY_SCALE = 0.0043

/**
 * Where the procedural glasses' lenses sit for this head (mirrors createGlasses in
 * avatarCustomization), in Head space. Eyes are fitted inside so they never
 * overlap the frames or poke in front of the glass.
 */
function measureLenses(model: THREE.Object3D, headBone: THREE.Bone, style: string) {
  const fit = measureHeadFit(model, headBone, RIGGED_ACCESSORY_SCALE)
  if (!fit) return null
  const s = RIGGED_ACCESSORY_SCALE
  const maxOuter = fit.faceHalfWidth * 0.93
  const lensRadius = Math.min(0.1, Math.max(0.05, fit.eyeX * 0.82), Math.max(0.05, maxOuter - fit.eyeX))
  const eyeX = Math.max(lensRadius * 0.9, Math.min(fit.eyeX, maxOuter - lensRadius))
  const aviator = style === 'aviator'
  return {
    x: eyeX * s,
    y: fit.eyeY * s,
    /** Lens plane depth at the lens centre (Head units). */
    z: (fit.eyeFront + 0.024) * s,
    rx: lensRadius * s * (aviator ? 1.06 * 1.05 : 1),
    ry: lensRadius * s * (aviator ? 1.06 * 0.84 : 1),
    tilt: 0.22,
  }
}

const EYE_DOME_SCALE = new THREE.Vector3(0.64, 0.5, 0.36)
const EYE_APERTURE_HALF_WIDTH = 0.5
const SKIN_SATURATION = 0.88
/** Where the moustache's lower edge sits above the (lowered) mouth, in eye radii. */
const HAIR_EDGE_OFFSET = 0.3
/** Extra mouth-corner lift under facial hair (the moustache hides most of the smile). */
const FACIAL_HAIR_SMILE_BIAS = 0.12

export function createAvatarFace(
  model: THREE.Object3D,
  headBone: THREE.Bone | undefined,
  materials: readonly THREE.Material[],
  skinColor: THREE.Color | null,
  eyewear: 'none' | 'round' | 'aviator' | 'shades' | string = 'none',
  seed = 0.5,
  profile?: Partial<FacePersonalityInput>
): AvatarFaceRig | null {
  if (!headBone) return null
  const eyePoints = collectRegion(model, headBone, /^eye$/i)
  if (eyePoints.length < 6) return null
  const browPoints = collectRegion(model, headBone, /^eyebrows?$/i)

  const { center, left, right } = splitBySide(eyePoints)
  if (!left || !right) return null
  // Face forward in Head space: from the head origin through the eyes, flattened.
  const forward = new THREE.Vector3(center.x * 0, 0, center.z).normalize()
  if (forward.lengthSq() < 0.5) forward.set(0, 0, 1)
  const quaternion = new THREE.Quaternion().setFromUnitVectors(new THREE.Vector3(0, 0, 1), forward)
  const basis = {
    right: new THREE.Vector3(1, 0, 0).applyQuaternion(quaternion),
    up: new THREE.Vector3(0, 1, 0).applyQuaternion(quaternion),
    forward: forward.clone(),
  }

  const created: THREE.Material[] = []
  const geometries: THREE.BufferGeometry[] = []
  const personality = getFacePersonality({ ...profile, seed })

  const eyeWidth = Math.max(left.max.x - left.min.x, right.max.x - right.min.x)
  const eyeHeight = Math.max(left.max.y - left.min.y, right.max.y - right.min.y)
  const radius = Math.max(eyeWidth, eyeHeight) * 1.05

  // The face surface around the eyes (skin in Head space), so the eyes sit *on*
  // the head instead of bulging out of it in profile.
  const skinPoints = collectRegion(model, headBone, /^skin$/i)
  const surface = createFaceSurface(model, headBone, forward, {
    minY: center.y - radius * 9,
    maxY: center.y + radius * 7,
    maxX: radius * 10,
  })

  const skinSource = (materials.find(material => /^skin$/i.test(material.name)) as THREE.MeshToonMaterial | undefined) ?? null
  const gradientMap = skinSource?.gradientMap ?? null
  const skin = skinColor ?? new THREE.Color('#d9a37c')

  // Brow / hair colour comes from the painted brows before they are hidden.
  const browMaterial = materials.find(material => /^eyebrows?$/i.test(material.name)) as THREE.MeshToonMaterial | undefined
  const browColor = browMaterial?.color ? browMaterial.color.clone() : new THREE.Color('#2a1a12')
  if (skinColor && Math.abs(browColor.r - skinColor.r) + Math.abs(browColor.g - skinColor.g) + Math.abs(browColor.b - skinColor.b) < 0.03) browColor.set('#2a1a12')
  const skinLuma = skin.r * 0.299 + skin.g * 0.587 + skin.b * 0.114
  const browContrast = skinLuma < 0.22 ? 1.4 : 1
  const hairMaterial = materials.find(material => /^(hair|moustache|mustache|beard)$/i.test(material.name)) as THREE.MeshToonMaterial | undefined

  // ---- eyes ----
  const lenses = eyewear === 'round' || eyewear === 'aviator' ? measureLenses(model, headBone, eyewear) : null
  const domeGeometry = createEyeDomeGeometry()
  geometries.push(domeGeometry)
  const [irisA, irisB] = IRIS_PALETTE[personality.iris]
  const lashColor = browColor.clone().multiplyScalar(0.55).lerp(new THREE.Color('#120806'), 0.55)
  const eyes: EyeRig[] = []
  const eyeCenters: THREE.Vector3[] = []
  const skinFollowers: THREE.MeshToonMaterial[] = []
  for (const [box, side] of [[right, 1], [left, -1]] as const) {
    const eyeCenter = box.getCenter(new THREE.Vector3())
    let rootScale = radius
    let protrude = radius * 0.17
    if (lenses) {
      // Sit centred behind the lens, small enough to clear the frame, well behind the glass.
      const lensCenterX = side * lenses.x
      if (Math.abs(lensCenterX - eyeCenter.x) < radius * 1.2) eyeCenter.x = lensCenterX
      if (Math.abs(lenses.y - eyeCenter.y) < radius * 1.2) eyeCenter.y = lenses.y
      const fitWidth = (lenses.rx * 0.8) / (EYE_APERTURE_HALF_WIDTH * 1.05)
      const fitHeight = (lenses.ry * 0.86) / 0.38
      rootScale = Math.min(radius, fitWidth, fitHeight)
      protrude = radius * 0.1
    }
    const surfaceDepth = surface.depthAt(eyeCenter.x, eyeCenter.y) ?? eyeCenter.dot(forward) + radius * 0.3
    if (lenses) {
      // Never let the dome reach the lens plane (minus the lens tilt at its outer edge).
      const lensDepth = lenses.z - Math.sin(lenses.tilt) * rootScale * 0.7
      const room = lensDepth - surfaceDepth - radius * 0.06
      protrude = Math.max(radius * 0.02, Math.min(protrude, room))
    }
    eyeCenters.push(eyeCenter)
    const root = new THREE.Group()
    root.name = 'cartoon-eye'
    const along = eyeCenter.dot(forward)
    root.position.copy(eyeCenter).addScaledVector(forward, surfaceDepth + protrude - rootScale * EYE_DOME_SCALE.z - along)
    // Follow the curve of the face: each eye turns slightly outward.
    root.quaternion.copy(quaternion).multiply(new THREE.Quaternion().setFromAxisAngle(new THREE.Vector3(0, 1, 0), side * 0.22))
    root.scale.setScalar(rootScale)

    const uniforms = createEyeUniforms(side)
    uniforms.uAper.value.z = EYE_APERTURE_HALF_WIDTH
    uniforms.uQScale.value.set(EYE_DOME_SCALE.x, EYE_DOME_SCALE.y)
    uniforms.uIrisA.value.set(irisA)
    uniforms.uIrisB.value.set(irisB)
    uniforms.uLash.value.copy(lashColor)
    const material = createEyeMaterial(uniforms, skin, gradientMap)
    created.push(material)
    skinFollowers.push(material as THREE.MeshToonMaterial)
    const dome = new THREE.Mesh(domeGeometry, material)
    dome.name = 'cartoon-eye-dome'
    dome.frustumCulled = false
    dome.scale.copy(EYE_DOME_SCALE)
    root.add(dome)
    headBone.add(root)
    eyes.push({ root, dome, uniforms, radius, side })
  }
  const eyeMid = eyeCenters[0]!.clone().lerp(eyeCenters[1]!, 0.5)

  // ---- mouth ----
  const mouthMaterial = new THREE.MeshToonMaterial({
    color: '#ffffff',
    vertexColors: true,
    side: THREE.DoubleSide,
    gradientMap,
    polygonOffset: true,
    polygonOffsetFactor: -2,
    polygonOffsetUnits: -2,
  })
  created.push(mouthMaterial)
  let mouthY = eyeMid.y - radius * 2.7
  const mouthHalfWidth = radius * 0.98
  // Facial hair (a moustache/beard mesh) hides a mouth that sits on the skin under it. Detect
  // it over the mouth's footprint; on those models the mouth drops just below the moustache
  // and sits in front of the hair, with tamer limits so it never pokes past it.
  let beardDepthGain = 0
  for (let c = 0; c < 13; c += 1) {
    const x = eyeMid.x + (c / 12 * 2 - 1) * mouthHalfWidth
    for (let k = -2; k <= 2; k += 1) {
      const y = mouthY + k * radius * 0.25
      const skinDepth = surface.depthAt(x, y)
      const hairDepth = surface.depthAt(x, y, true)
      if (skinDepth !== null && hairDepth !== null) beardDepthGain = Math.max(beardDepthGain, hairDepth - skinDepth)
    }
  }
  const hasFacialHair = beardDepthGain > radius * 0.12
  if (hasFacialHair) {
    // Step the mouth down until the centre of the lips is clear of the moustache (up to ~0.8r).
    mouthY -= radius * 0.3
    for (let step = 0; step < 2; step += 1) {
      const skinDepth = surface.depthAt(eyeMid.x, mouthY)
      const hairDepth = surface.depthAt(eyeMid.x, mouthY, true)
      if (skinDepth !== null && hairDepth !== null && hairDepth - skinDepth > radius * 0.12) mouthY -= radius * 0.25
    }
  }
  const colDepth = new Float32Array(13)
  for (let c = 0; c < 13; c += 1) {
    const x = eyeMid.x + (c / 12 * 2 - 1) * mouthHalfWidth
    let depth = surface.depthAt(x, mouthY) ?? surface.depthAt(eyeMid.x, mouthY) ?? eyeMid.dot(forward) - radius * 0.1
    if (hasFacialHair) {
      for (let k = -3; k <= 3; k += 1) {
        const hair = surface.depthAt(x, mouthY + k * radius * 0.22, true)
        if (hair !== null) depth = Math.max(depth, hair)
      }
    }
    colDepth[c] = depth + radius * (hasFacialHair ? 0.11 : 0.05)
  }
  // A rigid moustache reads as a grin: bend it with the mouth corners, and shade it when it is
  // light (see avatarFaceHair.ts).
  let hairShade: FacialHairShade | null = null
  if (hasFacialHair && hairMaterial && hairMaterial.color) {
    const hairLuma = hairMaterial.color.r * 0.299 + hairMaterial.color.g * 0.587 + hairMaterial.color.b * 0.114
    let hairMesh: THREE.SkinnedMesh | null = null
    model.traverse(object => {
      const mesh = object as THREE.SkinnedMesh
      if (!hairMesh && mesh.isSkinnedMesh && !Array.isArray(mesh.material) && mesh.material === hairMaterial) hairMesh = mesh
    })
    const hm = hairMesh as THREE.SkinnedMesh | null
    const hi = hm ? hm.skeleton.bones.indexOf(headBone) : -1
    if (hm && hi >= 0) {
      const toHead = new THREE.Matrix4().multiplyMatrices(hm.skeleton.boneInverses[hi]!, hm.bindMatrix)
      const edgeY = mouthY + radius * HAIR_EDGE_OFFSET
      let outline: THREE.SkinnedMesh | null = null
      model.traverse(object => {
        const mesh = object as THREE.SkinnedMesh
        if (!outline && mesh.isSkinnedMesh && mesh.name === `${hm.name}-outline`) outline = mesh
      })
      hairShade = installFacialHairShade(hairMaterial, hm, toHead, edgeY, radius, eyeMid.x, {
        light: hairLuma > 0.35,
        outline,
      })
    }
  }
  const mouthGeometry = createMouthGeometry()
  geometries.push(mouthGeometry.geometry)
  const mouthOrigin = new THREE.Vector3(eyeMid.x, mouthY, 0)
  // Remove the forward component from the origin: depth is added per column.
  mouthOrigin.addScaledVector(forward, -mouthOrigin.dot(forward))
  const mouth = createMouth({
    ...mouthGeometry,
    material: mouthMaterial,
    halfWidth: mouthHalfWidth,
    lip: radius * (hasFacialHair ? 0.11 : 0.15),
    origin: mouthOrigin,
    forward: basis.forward,
    right: basis.right,
    up: basis.up,
    colDepth,
    skinColor: skin,
    hairColor: null,
    toneAmount: personality.lipTone,
    facialHair: hasFacialHair,
  })
  const moustache = hairShade?.moustache ?? null
  if (moustache) {
    // The lips never draw over the moustache: the mouth is clipped to its (bent) lower edge.
    const edge = new Float32Array(moustache.lowerEdge.length)
    for (let b = 0; b < edge.length; b += 1) edge[b] = moustache.lowerEdge[b]! - mouthY
    mouth.hairClip = { edge, halfWidth: moustache.halfWidth * radius, liftL: 0, liftR: 0, centre: 0 }
  }
  headBone.add(mouth.mesh)

  // ---- brows + skin decals (one overlay mesh) ----
  const browSplit = browPoints.length > 6 ? splitBySide(browPoints) : null
  const browSpecs = eyes.map((eye, i) => {
    const painted = eye.side === 1 ? browSplit?.right : browSplit?.left
    const eyeCenter = eyeCenters[i]!
    const paintedCenter = painted?.getCenter(new THREE.Vector3())
    const restY = paintedCenter
      ? THREE.MathUtils.clamp(paintedCenter.y, eyeCenter.y + radius * 0.46, eyeCenter.y + radius * 0.95)
      : eyeCenter.y + radius * 0.66
    const paintedWidth = painted ? painted.max.x - painted.min.x : radius * 1.4
    return {
      side: eye.side,
      cx: eyeCenter.x + eye.side * radius * 0.1,
      // Behind opaque shades the brows sit above the frames, not through the lenses.
      // Behind glasses the brows sit a touch lower, so a hard hat's brim or a fringe never swallows them.
      cy: lenses ? restY - radius * 0.02 : restY + (eyewear === 'shades' ? radius * 0.34 : 0),
      length: THREE.MathUtils.clamp(paintedWidth * 1.1, radius * 1.15, radius * 1.65),
      thickness: radius * 0.22 * personality.browThickness,
    }
  })
  const mouthCorner = radius * 0.98 * 0.98
  const noseX = eyeMid.x
  const eyeY = eyeMid.y
  const r = radius
  const decal = (
    kind: DecalKind, x: number, y: number, hw: number, hh: number, rot: number, sprite: 'blob' | 'line', color: string
  ): DecalSpec => ({ kind, x, y, hw, hh, rot, sprite, color })
  const creaseAngle = (side: number) => {
    // From beside the nose down to the mouth corner.
    const from = { x: noseX + side * r * 0.62, y: eyeY - r * 1.5 }
    const to = { x: noseX + side * mouthCorner, y: mouthY + r * 0.18 }
    return {
      x: (from.x + to.x) / 2, y: (from.y + to.y) / 2,
      hw: Math.hypot(to.x - from.x, to.y - from.y) / 2,
      rot: Math.atan2(to.y - from.y, to.x - from.x),
    }
  }
  const creasePos = creaseAngle(1)
  const creaseNeg = creaseAngle(-1)
  const decalSpecs: DecalSpec[] = [
    decal('pallor', noseX, eyeY - r * 0.9, r * 1.9, r * 2.2, 0, 'blob', '#a9b7a4'),
    decal('blushA', noseX + r * 1.75, eyeY - r * 1.3, r * 1.15, r * 0.9, 0, 'blob', '#ff5a58'),
    decal('blushB', noseX - r * 1.75, eyeY - r * 1.3, r * 1.15, r * 0.9, 0, 'blob', '#ff5a58'),
    decal('bagA', eyeCenters[0]!.x, eyeCenters[0]!.y - r * 0.74, r * 0.66, r * 0.2, 0, 'blob', '#8a4f58'),
    decal('bagB', eyeCenters[1]!.x, eyeCenters[1]!.y - r * 0.74, r * 0.66, r * 0.2, 0, 'blob', '#8a4f58'),
    decal('nose', noseX, eyeY - r * 1.15, r * 0.24, r * 0.55, 0, 'blob', '#ffffff'),
    decal('forehead', noseX, eyeY + r * 1.95, r * 1.25, r * 0.55, 0, 'blob', '#ffffff'),
    decal('cheekA', noseX + r * 1.6, eyeY - r * 0.95, r * 0.5, r * 0.3, 0.35, 'blob', '#ffe2c8'),
    decal('cheekB', noseX - r * 1.6, eyeY - r * 0.95, r * 0.5, r * 0.3, -0.35, 'blob', '#ffe2c8'),
    decal('creaseA', creasePos.x, creasePos.y, creasePos.hw, r * 0.16, creasePos.rot, 'line', '#4a2418'),
    decal('creaseB', creaseNeg.x, creaseNeg.y, creaseNeg.hw, r * 0.16, creaseNeg.rot, 'line', '#4a2418'),
    decal('furrow', noseX, eyeY + r * 0.8, r * 0.36, r * 0.13, Math.PI / 2, 'line', '#4a2418'),
    decal('noseWrinkle', noseX, eyeY - r * 0.4, r * 0.5, r * 0.11, 0, 'line', '#4a2418'),
  ]
  const atlasTexture = acquireOverlayAtlas()
  const overlayMaterial = createOverlayMaterial(atlasTexture, gradientMap)
  created.push(overlayMaterial)
  const overlay = createOverlay({
    material: overlayMaterial,
    radius,
    basis,
    browSpecs,
    depthAt: (x, y) => surface.depthAt(x, y) ?? eyeMid.dot(forward) + r * 0.1,
    decalSpecs,
    browColor,
  })
  headBone.add(overlay.mesh)

  // Gentle skin grade: knock the saturation back a touch so warm skins stop reading as brick
  // red. Wrapped on the shared skin material (hands and body too) and undone on dispose.
  let restoreSkin: (() => void) | null = null
  if (skinSource) {
    const previous = skinSource.onBeforeCompile
    const previousKey = skinSource.customProgramCacheKey
    skinSource.onBeforeCompile = (shader, renderer) => {
      previous.call(skinSource, shader, renderer)
      shader.fragmentShader = shader.fragmentShader.replace(
        '#include <opaque_fragment>',
        `{ float skinLuma = dot(outgoingLight, vec3(0.299, 0.587, 0.114)); outgoingLight = mix(vec3(skinLuma), outgoingLight, ${SKIN_SATURATION.toFixed(2)}); }
#include <opaque_fragment>`
      )
    }
    skinSource.customProgramCacheKey = () => 'avatar-skin-grade-v1'
    skinSource.needsUpdate = true
    restoreSkin = () => {
      skinSource.onBeforeCompile = previous
      skinSource.customProgramCacheKey = previousKey
      skinSource.needsUpdate = true
    }
  }
  paintOver(materials, /^eye$/i, skinColor)
  paintOver(materials, /^eyebrows?$/i, skinColor)
  // The painted eye/brow patches are little raised slabs that catch the light as pale
  // rectangles once real brows sit on top: drop them (the skin underneath is intact).
  const hidden: THREE.Material[] = []
  for (const material of materials) {
    if (/^(eye|eyebrows?)$/i.test(material.name) && material.visible) {
      material.visible = false
      hidden.push(material)
    }
  }
  if (skinSource) {
    for (const material of materials) {
      if (/^(eye|eyebrows?)$/i.test(material.name) && (material as THREE.MeshToonMaterial).color) {
        skinFollowers.push(material as THREE.MeshToonMaterial)
      }
    }
  }

  // Opaque sunglasses hide the eyes (and brows sit above the frames).
  const shaded = eyewear === 'shades'
  for (const eye of eyes) eye.root.visible = !shaded

  // Forehead spot: above the brows, on the skin surface (measured, like the eyes).
  // Sized from the head's width at eye level, sitting just above the brows / glasses frames.
  let skinMinX = Infinity
  let skinMaxX = -Infinity
  let skinTop = -Infinity
  for (const point of skinPoints) {
    skinTop = Math.max(skinTop, point.y)
    if (Math.abs(point.y - center.y) < radius * 1.5) {
      skinMinX = Math.min(skinMinX, point.x)
      skinMaxX = Math.max(skinMaxX, point.x)
    }
  }
  const headWidth = Number.isFinite(skinMinX) && skinMaxX > skinMinX ? skinMaxX - skinMinX : radius * 7
  const foreheadSize = headWidth * 0.6
  const foreheadY = Math.min(
    center.y + radius * 2.4 + foreheadSize * 0.5,
    Number.isFinite(skinTop) ? skinTop - foreheadSize * 0.3 : Infinity
  )
  const foreheadProbe = new THREE.Vector3(center.x, Math.max(foreheadY, center.y + radius * 1.8), 0)
  let foreheadDepth = -Infinity
  for (const point of skinPoints) {
    if (Math.abs(point.x - foreheadProbe.x) < radius * 2 && Math.abs(point.y - foreheadProbe.y) < radius * 1.2) {
      foreheadDepth = Math.max(foreheadDepth, point.dot(forward))
    }
  }
  if (!Number.isFinite(foreheadDepth)) foreheadDepth = center.dot(forward) + radius * 0.2
  const foreheadPosition = foreheadProbe.clone().addScaledVector(forward, foreheadDepth + radius * 0.12 - foreheadProbe.dot(forward))
  // The forehead leans back: tip the sticker's normal up a little.
  const foreheadQuaternion = quaternion.clone().multiply(new THREE.Quaternion().setFromAxisAngle(new THREE.Vector3(1, 0, 0), -0.28))

  const input: FaceInput = { delta: 0, blink: 0, lookX: 0, lookY: 0, reducedMotion: false }
  const context = createFaceContext()
  const targets = createGazeTargets()
  return {
    headBone,
    forehead: { position: foreheadPosition, quaternion: foreheadQuaternion, unit: radius, size: foreheadSize },
    eyes,
    overlay,
    mouth,
    materials: created,
    geometries,
    skinFollowers,
    skinSource,
    personality,
    emotion: createEmotionState(seed),
    gazeState: createGazeState(seed),
    gazeTargets: targets,
    input,
    context,
    targets,
    gazeEyes: eyes.map(eye => ({ position: eye.root.position, quaternion: eye.root.quaternion, baseYaw: eye.side * 0.22 })),
    gazeOpts: { instant: false, heavy: 0, fallbackYaw: 0, fallbackPitch: 0, tripping: false, drunk: 0, closed: false, still: false },
    eyewear,
    hiddenMaterials: hidden,
    browContrast,
    restoreSkin,
    hairShade,
    skeletons: collectSkeletons(model),
    sceneHooked: false,
    scene: null,
    emote: null,
    state: {
      seed,
      time: 0,
      frame: 0,
      accumDelta: 0,
      strideFrame: 0,
      phase: Math.floor(seed * 1000) % 3,
      dim: 1,
      pupil: 0,
      debugWeights: new Float32Array(EMOTION_COUNT),
      lossStreak: 0,
      prevLoser: false,
      prevWinner: false,
      lastBrowAlpha: -1,
      mouthShape: { cornerL: 0, cornerR: 0, open: 0, width: 1, press: 0, purse: 0, teeth: 0, shift: 0 },
      browParams: { inner: [0, 0], outer: [0, 0], arch: 0, furrow: 0, dip: [0, 0], thick: 1 },
      alphas: {},
    },
  }
}

